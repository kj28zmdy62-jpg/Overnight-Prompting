"""Writes GeneratedModels.java from ENTITY_MODELS so Java geometry matches the textures."""
import os
import assets as A

JAVA = os.path.join(A.ROOT, "src", "client", "java", "com", "noclip", "client", "model", "GeneratedModels.java")


def f(x):
    return f"{float(x)}F"


def write():
    lines = [
        "package com.noclip.client.model;",
        "",
        "import net.minecraft.client.model.geom.PartPose;",
        "import net.minecraft.client.model.geom.builders.CubeDeformation;",
        "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
        "import net.minecraft.client.model.geom.builders.LayerDefinition;",
        "import net.minecraft.client.model.geom.builders.MeshDefinition;",
        "import net.minecraft.client.model.geom.builders.PartDefinition;",
        "",
        "import java.util.HashMap;",
        "import java.util.Map;",
        "import java.util.function.Supplier;",
        "",
        "/** GENERATED by tools/gen_models.py - do not edit. */",
        "public final class GeneratedModels {",
        "    public static final Map<String, Supplier<LayerDefinition>> LAYERS = new HashMap<>();",
        "",
        "    private GeneratedModels() {}",
        "",
        "    static {",
    ]
    for name in sorted(A.ENTITY_MODELS):
        lines.append(f'        LAYERS.put("{name}", GeneratedModels::{name});')
    lines.append("    }")
    for name, m in sorted(A.ENTITY_MODELS.items()):
        tw, th = m["tex"]
        lines += ["", f"    public static LayerDefinition {name}() {{",
                  "        MeshDefinition mesh = new MeshDefinition();",
                  "        PartDefinition root = mesh.getRoot();"]
        defined = {"root"}
        pending = list(m["parts"])
        while pending:
            progressed = False
            for p in list(pending):
                parent = p["parent"] or "root"
                if parent not in defined:
                    continue
                cubes = "CubeListBuilder.create()"
                for c in p["cubes"]:
                    u, v, x, y, z, w, h, d = c[:8]
                    inflate = c[8] if len(c) > 8 else 0
                    mirror = c[9] if len(c) > 9 else False
                    cubes += f".texOffs({u}, {v})"
                    if mirror:
                        cubes += ".mirror()"
                    cubes += f".addBox({f(x)}, {f(y)}, {f(z)}, {f(w)}, {f(h)}, {f(d)}, new CubeDeformation({f(inflate)}))"
                    if mirror:
                        cubes += ".mirror(false)"
                px, py, pz = p["pivot"]
                rx, ry, rz = p["rot"]
                var = "p_" + p["name"]
                parent_var = "root" if parent == "root" else "p_" + parent
                lines.append(f'        PartDefinition {var} = {parent_var}.addOrReplaceChild("{p["name"]}", {cubes}, '
                             f'PartPose.offsetAndRotation({f(px)}, {f(py)}, {f(pz)}, {f(rx)}, {f(ry)}, {f(rz)}));')
                defined.add(p["name"])
                pending.remove(p)
                progressed = True
            if not progressed:
                raise ValueError(f"model {name}: unresolved parents {[p['name'] for p in pending]}")
        lines += [f"        return LayerDefinition.create(mesh, {tw}, {th});", "    }"]
    lines.append("}")
    os.makedirs(os.path.dirname(JAVA), exist_ok=True)
    src = "\n".join(lines) + "\n"
    # unused PartDefinition variables are fine for javac
    with open(JAVA, "w") as fh:
        fh.write(src)
