def text_width(s, scale=1, gap=1):
    return len(s) * (3 * scale + gap) - gap


def text_mask(s, w=32, h=32, scale=1, x=None, y=None, gap=1, jitter_seed=None):
    """Boolean-ish mask with the string drawn into a (h, w) field, centred unless x/y given."""
    m = np.zeros((h, w))
    tw = text_width(s, scale, gap)
    x0 = (w - tw) // 2 if x is None else x
    y0 = (h - 5 * scale) // 2 if y is None else y
    r = T.rng("jit", jitter_seed) if jitter_seed else None
    cx = x0
    for ch in s.upper():
        g = GLYPHS.get(ch, GLYPHS["?"])
        dy = int(r.integers(-1, 2)) if r is not None else 0
        for gy, row in enumerate(g):
            for gx, c in enumerate(row):
                if c == "1":
                    yy, xx = y0 + dy + gy * scale, cx + gx * scale
                    m[max(0, yy):max(0, yy + scale), max(0, xx):max(0, xx + scale)] = 1
        cx += 3 * scale + gap
    return m


def draw(img, s, color, scale=1, x=None, y=None, alpha=1.0, gap=1, jitter_seed=None):
    h, w = img.shape[:2]
    m = text_mask(s, w, h, scale, x, y, gap, jitter_seed) * alpha
    return T.blend(img, T.solid(color, shape=(h, w)), m)
