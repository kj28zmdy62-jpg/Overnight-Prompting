"""Generates Java index classes by scanning sources, so levels and entities can be
added by dropping in a file. No shared registry file to edit, no merge conflicts.

  levels/*.java with `public static BackroomsLevel create()`  -> LevelIndex
  entity/*.java with `public static void register()`          -> EntityIndex
  client/render/entities/*.java with `public static void register()` -> ClientEntityIndex
"""
import os
import re
import assets as A

MAIN = os.path.join(A.ROOT, "src", "main", "java", "com", "noclip")
CLIENT = os.path.join(A.ROOT, "src", "client", "java", "com", "noclip", "client")


def scan(folder, pattern):
    out = []
    if not os.path.isdir(folder):
        return out
    for f in sorted(os.listdir(folder)):
        if f.endswith(".java"):
            src = open(os.path.join(folder, f)).read()
            if re.search(pattern, src):
                out.append(f[:-5])
    return out


def write(path, package, cls, imports, body):
    lines = [f"package {package};", ""] + [f"import {i};" for i in imports] + ["",
             "/** GENERATED by tools/gen_index.py - do not edit. */",
             f"public final class {cls} {{", f"    private {cls}() {{}}", ""] + body + ["}"]
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def run():
    levels = scan(os.path.join(MAIN, "levels"), r"public static BackroomsLevel create\(\)")
    write(os.path.join(MAIN, "levels", "LevelIndex.java"), "com.noclip.levels", "LevelIndex",
          ["com.noclip.level.Levels"],
          ["    public static void registerAll() {"] +
          [f"        Levels.register({c}.create());" for c in levels] + ["    }"])
    ents = scan(os.path.join(MAIN, "entity"), r"public static void register\(\)")
    write(os.path.join(MAIN, "entity", "EntityIndex.java"), "com.noclip.entity", "EntityIndex", [],
          ["    public static void registerAll() {"] + [f"        {c}.register();" for c in ents] + ["    }"])
    folder = os.path.join(CLIENT, "render", "entities")
    os.makedirs(folder, exist_ok=True)
    rens = scan(folder, r"public static void register\(\)")
    write(os.path.join(folder, "ClientEntityIndex.java"), "com.noclip.client.render.entities", "ClientEntityIndex", [],
          ["    public static void registerAll() {"] + [f"        {c}.register();" for c in rens] + ["    }"])
    return len(levels), len(ents), len(rens)
